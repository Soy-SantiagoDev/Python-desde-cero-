# int() convierte el dato ingresado por el usuario de texto a un número entero.
edad = int(input("¿Cuál es tu edad? "))

# if evalúa una condición. Si la condición es verdadera,
# se ejecuta el bloque de código que está debajo.
if edad >= 18:
    # Se ejecuta cuando la edad es 18 o mayor.
    print("Eres mayor de edad.")
else:
    # else se ejecuta cuando la condición del if es falsa.
    print("Eres menor de edad.")
