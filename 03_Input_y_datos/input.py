# input() es una función que muestra un mensaje en pantalla
# y espera a que el usuario escriba un dato. Lo que el usuario
# escribe se guarda como texto (cadena o string).

nombre = input("¿Cuál es tu nombre? ")
# nombre: variable donde se almacena el dato ingresado por el usuario.
# = : operador de asignación, guarda el resultado de input() en la variable.
# "¿Cuál es tu nombre? " : mensaje que se muestra al usuario.

# print() es una función que muestra información en la pantalla.
# "Hola" es un texto fijo y nombre es la variable que contiene
# el nombre ingresado por el usuario.
print("Hola", nombre)
