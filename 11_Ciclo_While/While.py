# =====================================
# Ciclo WHILE
# =====================================
# El ciclo while permite repetir un
# bloque de código mientras una condición
# sea verdadera.
# =====================================

# Crear un contador.

contador = 1

# Repetir mientras el contador
# sea menor o igual a 10.

while contador <= 10:
    print(f"Repetición número {contador}")

    # Aumentar el contador en 1.
    contador += 1

# Este mensaje se ejecuta cuando
# el ciclo termina.

print("Fin del programa.")
