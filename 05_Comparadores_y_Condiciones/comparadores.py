# Operadores de comparación en Python
# ==  Igual que
# !=  Diferente de
# >   Mayor que
# <   Menor que
# >=  Mayor o igual que
# <=  Menor o igual que

edad= int(input("¿cuantos años tienes?"))

if edad == 18:
    print("tienes exactamente 18 años ")

if edad >18:
    print("eres mayor de edad")

if edad <18:
    print("eres menor de edad")

if edad != 18:
    print("no tienes 18 años ")